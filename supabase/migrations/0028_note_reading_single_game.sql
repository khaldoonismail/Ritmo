-- One shared "Note Reading" game whose questions are generated fresh every
-- time it's played (lib/noteReading.ts), instead of one saved game per
-- setting:
--   * games.generator marks a game whose questions are generated at play
--     time; its own `questions` stays '[]'.
--   * Team Battle: the host generates the round's questions when starting
--     and saves them in session_questions (one row per session). Not in
--     game_sessions itself, because game_sessions has a public select
--     policy (0020_team_battle.sql) and the questions carry correctIndex.
--   * Assignments: the teacher's chosen settings go in
--     assignments.game_settings; each student's own set is generated by the
--     server the first time they open it and kept in
--     assignment_question_sets (service role only).
--   * game_results.variant labels a result with the settings that affect
--     difficulty (e.g. 'treble-easy', 'mixed-hard-accidentals'), so the
--     leaderboard ranks each setting separately.
--
-- Additive only: new nullable columns, two new tables, one new game row,
-- and new versions of team_battle_advance and record_team_battle_results
-- with the same signatures and grants. For games without generated
-- questions (every game that exists today) both behave exactly as before:
-- team_battle_advance falls back to the game's own question count, and
-- variant is left null.

alter table public.games add column if not exists generator text
  check (generator in ('note_reading'));
alter table public.assignments add column if not exists game_settings jsonb;
alter table public.game_results add column if not exists variant text;

-- ---------------------------------------------------------------------------
-- Team Battle: one session's generated questions (host only)
-- ---------------------------------------------------------------------------
create table if not exists public.session_questions (
  session_id uuid primary key references public.game_sessions (id) on delete cascade,
  questions jsonb not null,
  created_at timestamptz not null default now()
);

alter table public.session_questions enable row level security;

-- The host reads and writes its own sessions' questions. Students never
-- read this table; the question/answer routes use the service role and
-- strip correctIndex as they already do.
create policy "session_questions_select_own" on public.session_questions
  for select using (
    session_id in (
      select gs.id from public.game_sessions gs
      join public.teachers t on t.id = gs.teacher_id
      where t.auth_user_id = auth.uid()
    )
  );

create policy "session_questions_insert_own" on public.session_questions
  for insert with check (
    session_id in (
      select gs.id from public.game_sessions gs
      join public.teachers t on t.id = gs.teacher_id
      where t.auth_user_id = auth.uid()
    )
  );

-- ---------------------------------------------------------------------------
-- Assignments: each student's own generated set (service role only)
-- ---------------------------------------------------------------------------
create table if not exists public.assignment_question_sets (
  assignment_id uuid not null references public.assignments (id) on delete cascade,
  student_id uuid not null references public.students (id) on delete cascade,
  questions jsonb not null,
  created_at timestamptz not null default now(),
  primary key (assignment_id, student_id)
);

-- RLS on with no policies: only the service-role routes
-- (app/student/game/[assignmentId], submit-game) can read or write it.
alter table public.assignment_question_sets enable row level security;

-- ---------------------------------------------------------------------------
-- The shared game
-- ---------------------------------------------------------------------------
-- Owned by an explicit teacher (Khaldoon, the main account). Fails loudly
-- if that teacher doesn't exist rather than silently skipping, and does
-- nothing if a Note Reading game already exists. Created private: it's made
-- public (is_public = true) only once the app code that generates its
-- questions is deployed, so the older code never lists an empty game.
do $$
declare
  v_owner uuid := 'b564f2b4-38b5-4a5b-ad57-43e1c90098f8';
begin
  if not exists (select 1 from public.teachers where id = v_owner) then
    raise exception 'Note Reading owner teacher % not found', v_owner;
  end if;
  if not exists (select 1 from public.games where generator = 'note_reading') then
    insert into public.games (teacher_id, title, questions, tags, is_public, generator)
    values (v_owner, 'Note Reading', '[]'::jsonb, '{note-reading}', false, 'note_reading');
  end if;
end;
$$;

-- ---------------------------------------------------------------------------
-- team_battle_advance (replaces 0026's version, same signature and grant)
-- ---------------------------------------------------------------------------
-- Only change: the question count comes from the session's generated
-- questions when it has them, else from the game as before.
create or replace function public.team_battle_advance(
  p_session_id uuid,
  p_from_index integer,
  p_skip_countdown boolean
) returns timestamptz
language plpgsql
security definer
set search_path = public
as $$
declare
  v_now timestamptz := now();
  v_total integer;
begin
  if not exists (
    select 1 from public.game_sessions gs
    where gs.id = p_session_id
      and gs.teacher_id in (select id from public.teachers where auth_user_id = auth.uid())
  ) then
    raise exception 'Not authorized to modify this session';
  end if;

  select coalesce(jsonb_array_length(sq.questions), jsonb_array_length(g.questions)) into v_total
  from public.game_sessions gs
  join public.games g on g.id = gs.game_id
  left join public.session_questions sq on sq.session_id = gs.id
  where gs.id = p_session_id;

  update public.game_sessions gs
  set status = case when p_from_index + 1 >= v_total then 'final'::public.session_status
                    else 'question'::public.session_status end,
      current_question_index = case when p_from_index + 1 >= v_total then gs.current_question_index
                                    else p_from_index + 1 end,
      question_started_at = case when p_from_index + 1 >= v_total then gs.question_started_at else v_now end,
      paused_seconds = case when p_from_index + 1 >= v_total then gs.paused_seconds else 0 end,
      time_extension_seconds = case when p_from_index + 1 >= v_total then gs.time_extension_seconds else 0 end,
      ended_at = case when p_from_index + 1 >= v_total then v_now else gs.ended_at end,
      paused_at = null,
      reveal_started_at = null,
      reveal_paused_seconds = 0
  where gs.id = p_session_id
    and gs.status = 'reveal'
    and gs.current_question_index = p_from_index
    and (
      p_skip_countdown
      or (
        coalesce((gs.settings ->> 'autoAdvance')::boolean, false)
        and gs.paused_at is null
        and gs.reveal_started_at is not null
        and extract(epoch from (v_now - gs.reveal_started_at)) - gs.reveal_paused_seconds
            >= coalesce((gs.settings ->> 'revealSeconds')::numeric, 5)
      )
    );

  return v_now;
end;
$$;

-- ---------------------------------------------------------------------------
-- record_team_battle_results (replaces 0025's version, same signature)
-- ---------------------------------------------------------------------------
-- Only change: also records the session's difficulty label
-- (settings.variant, set by the host for generated games; null otherwise).
-- create or replace keeps 0025's revoke, so still only the trigger calls it.
create or replace function public.record_team_battle_results(p_session_id uuid)
returns void
language sql
security definer
set search_path = public
as $$
  with played as (
    select count(distinct question_index)::int as total
    from public.game_answers
    where session_id = p_session_id
  ),
  per_student as (
    select gp.student_id,
           gp.score,
           count(ga.id) filter (where ga.is_correct)::int as correct
    from public.game_participants gp
    join public.game_answers ga on ga.participant_id = gp.id
    where gp.session_id = p_session_id
    group by gp.student_id, gp.score
  )
  insert into public.game_results (
    student_id, class_id, game_id, source, session_id,
    points, correct_count, total_questions, accuracy, completed_at, variant
  )
  select ps.student_id,
         st.class_id,
         gs.game_id,
         'team_battle',
         gs.id,
         ps.score,
         ps.correct,
         played.total,
         case when played.total > 0 then round(100.0 * ps.correct / played.total, 2) else 0 end,
         coalesce(gs.ended_at, now()),
         nullif(gs.settings ->> 'variant', '')
  from per_student ps
  join public.students st on st.id = ps.student_id
  join public.game_sessions gs on gs.id = p_session_id
  cross join played
  where gs.play_mode = 'team_battle'
  on conflict (session_id, student_id)
  do update set
    points = excluded.points,
    correct_count = excluded.correct_count,
    total_questions = excluded.total_questions,
    accuracy = excluded.accuracy,
    completed_at = excluded.completed_at,
    variant = excluded.variant;
$$;
